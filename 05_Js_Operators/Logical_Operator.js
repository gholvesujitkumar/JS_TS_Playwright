// !! (logical NOT operator)
// The logical NOT operator (!) is used to invert the boolean value
// && (logical AND operator)
// The logical AND operator (&&) is used to combine two boolean values
// and return true only if both values are true.
// || (logical OR operator)
// The logical OR operator (||) is used to combine two boolean values
// and return true if at least one of the values is true.

let a = true;
let b = false;

console.log(!a); // false
console.log(a && b); // false
console.log(a || b); // true